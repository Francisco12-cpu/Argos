/** Faixas de índices que viram um nome só. */
const RANGES = [
  [152, 269, 'cachorro'], // raças de cachorro
  [282, 286, 'gato'],
  [292, 293, 'felino'],
  [295, 298, 'urso'],
  [31, 33, 'sapo'],
  [35, 38, 'tartaruga'],
  [53, 66, 'cobra'],
  [73, 78, 'aranha'],
  [119, 126, 'caranguejo'],
  [322, 327, 'borboleta'],
  [368, 383, 'macaco'],
  [386, 387, 'elefante'],
];

/** Nome em português do palpite, ou null se a categoria não é do dia a dia. */
export function imagenetPt(index) {
  if (Object.hasOwn(SINGLE, index)) return SINGLE[index];
  for (const [from, to, name] of RANGES) if (index >= from && index <= to) return name;
  return null;
}

/**
 * Junta as probabilidades das categorias que viram o mesmo nome em
 * português ("tabby" + "tiger cat" = "gato") e devolve o melhor palpite.
 * @param {Array<{index: number, score: number}>} top
 * @returns {{name: string, score: number} | null}
 */
export function bestGuess(top) {
  const totals = new Map();
  for (const { index, score } of top) {
    const name = imagenetPt(index);
    if (name) totals.set(name, (totals.get(name) ?? 0) + score);
  }
  let best = null;
  for (const [name, score] of totals) if (!best || score > best.score) best = { name, score };
  return best;
}
